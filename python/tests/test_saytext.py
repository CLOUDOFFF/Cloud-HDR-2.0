r"""Проверка текста для голоса: цифры, латиница и сокращения → слова.

Запуск из папки python:  ..\runtime\python.exe -m tests.test_saytext
"""
import sys

sys.path.insert(0, '.')

from cloudhdr_saytext import say  # noqa: E402

CASES = [
    ('Готово', 'Готово.'),
    ('Ответ за 0,6 секунды', 'Ответ за ноль целых шесть десятых секунды.'),
    ('Будильник на 7:05', 'Будильник на семь ноль пять.'),
    ('Встреча в 14:30', 'Встреча в четырнадцать тридцать.'),
    ('Загрузка процессора 45%', 'Загрузка процессора сорок пять процентов.'),
    ('Осталось 1%', 'Осталось один процент.'),
    ('Свободно 3 процента', 'Свободно три процента.'),
    ('Через 1 минуту', 'Через одну минуту.'),
    ('Прошло 2 минуты', 'Прошло две минуты.'),
    ('Нашёл 2 файла', 'Нашёл два файла.'),
    ('Открыл 21 вкладку', 'Открыл двадцать одну вкладку.'),
    ('Это 1-й шаг', 'Это первый шаг.'),
    ('Уже 2-я попытка', 'Уже вторая попытка.'),
    ('В 3.5 раза быстрее', 'В три целых пять десятых раза быстрее.'),
    ('Cloud HDR 2.0', 'клауд эйч ди ар два ноль.'),
    ('Открываю YouTube', 'Открываю ютуб.'),
    ('Запускаю Windows Update', 'Запускаю виндоус апдейт.'),
    ('Видеокарта RTX 5060', 'Видеокарта ар ти экс пять тысяч шестьдесят.'),
    ('Нагрузка на GPU', 'Нагрузка на джи пи ю.'),
    ('Подключи Wi-Fi', 'Подключи вайфай.'),
    ('Твой ПК готов', 'Твой пэ ка готов.'),
    ('Свободно 12 ГБ', 'Свободно двенадцать гигабайт.'),
    ('Цена 1 000 000 ₽', 'Цена один миллион рублей.'),
    ('Смотри https://example.com', 'Смотри ссылка.'),
    ('Это, т.е. всё', 'Это, то есть всё.'),
    ('Играю в Garry\'s Mod', 'Играю в гэррис мод.'),
]


def main() -> int:
    bad = 0
    for text, want in CASES:
        got = say(text)
        if got != want:
            bad += 1
            print(f'  НЕ ТАК  {text!r}\n          ждал  {want!r}\n          вышло {got!r}')
    # второй проход ничего не должен менять
    for text, _ in CASES:
        once = say(text)
        if say(once) != once:
            bad += 1
            print(f'  НЕ ИДЕМПОТЕНТНО  {text!r}: {once!r} → {say(once)!r}')
    print(f'{len(CASES) - bad}/{len(CASES)} верно' if bad else f'все {len(CASES)} верно')
    return 1 if bad else 0


if __name__ == '__main__':
    raise SystemExit(main())

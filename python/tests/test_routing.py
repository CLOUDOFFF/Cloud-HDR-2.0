def run(name, cases, fn):
    bad = 0
    for text, want in cases:
        got = fn(text)
        if got != want:
            bad += 1
            print(f'  [{name}] «{text}»: ждал {want or "—"}, получил {got or "—"}')
    return bad


if __name__ == '__main__':
    total = sum(len(c) for c in (SYSTEM, MEDIA, CLIP, APPS, FILES))
    bad = (run('sys', SYSTEM, match_system) + run('media', MEDIA, match_media) + run('clip', CLIP, match_clip)
           + run('apps', APPS, lambda t: match_apps(t)[0]) + run('files', FILES, lambda t: match_files(t)[0]))
    print(f'{total - bad}/{total} верно')
    sys.exit(1 if bad else 0)

def case_variants(word: str, limit: int = 3) -> List[str]:
    """
    Падежные формы слова через pymorphy3.

    Ради этого всё и затевалось: brain.js видит «загрузки» и «загрузок» как два
    независимых признака, а здесь формы одного слова попадают в обучение вместе
    и склеиваются на уровне лемм.
    """
    try:
        import pymorphy3
    except ImportError:
        return []

    global _MORPH
    if _MORPH is None:
        _MORPH = pymorphy3.MorphAnalyzer()

    parsed = _MORPH.parse(word)
    if not parsed:
        return []
    base = parsed[0]
    forms = []
    for case in ("accs", "gent", "loct", "datv", "ablt"):
        inflected = base.inflect({case})
        if inflected and inflected.word != word and inflected.word not in forms:
            forms.append(inflected.word)
    return forms[:limit]


_MORPH = None


# ================================================================== сборка ===

_BRAIN_ENTRY = re.compile(r"\[\s*'((?:[^'\\]|\\.)*)'\s*,\s*'([a-z_]+)'\s*\]")

_URL_RE = re.compile(
    r"(https?://\S+|(?:[a-z0-9-]+\.)+(?:ru|com|net|org|io|dev|me|tv|gg|app|xyz|info|biz|ua|by|kz|рф)(?:/\S*)?)",
    re.IGNORECASE,
)
_PATH_RE = re.compile(r"([a-zA-Z]:[\\/][^\s,]*|\\\\[^\s,]+)")


def harvest_brain() -> List[Example]:
    """
    603 фразы из brain.js. Метка намерения в них есть, границ цели нет —
    их восстанавливаем по словарю, а где словаря не хватило — по глаголу.
    Что не удалось совсем, помечается как «границы неизвестны» (см. Example).
    """
    source = BRAIN_JS.read_text(encoding="utf-8")
    lex = load_lexicon()
    app_aliases = sorted(lex.alias_to_app(), key=len, reverse=True)
    folder_aliases = sorted(lex.alias_to_folder(), key=len, reverse=True)

    examples: List[Example] = []
    unknown = 0
    for phrase, intent in _BRAIN_ENTRY.findall(source):
        phrase = phrase.replace("\\'", "'").strip()
        if not phrase or intent not in lex.intents:
            continue
        spans, missing = _align(phrase, intent, app_aliases, folder_aliases)
        unknown += missing
        examples.append(Example(phrase, intent, spans, "brain.js", ner_missing=missing))

    log(f"Из brain.js прочитано фраз: {len(examples)} "
        f"(границы цели неизвестны у {unknown} — разметчику они не мешают)")
    return examples


def harvest_feedback(path: Path, repeat: int = 12) -> List[Example]:
    """
    Поправки пользователя, накопленные сервисом («Не угадал?»).

    Повтор нужен из арифметики: одна исправленная фраза против 13 тысяч
    порождённых — это меньше сотой доли процента, и обучение её не заметит.
    Дюжина копий делает поправку различимой, но не даёт ей перевесить корпус,
    и границы цели у неё не размечены — только намерение, а его и поправляли.
    """
    if not path.exists():
        return []

    lex = load_lexicon()
    app_aliases = sorted(lex.alias_to_app(), key=len, reverse=True)
    folder_aliases = sorted(lex.alias_to_folder(), key=len, reverse=True)

    examples: List[Example] = []
    seen = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError:
            continue
        text, intent = str(record.get("text", "")).strip(), record.get("intent")
        if not text or intent not in lex.intents or (text, intent) in seen:
            continue
        seen.add((text, intent))
        spans, missing = _align(text, intent, app_aliases, folder_aliases)
        examples.extend(
            Example(text, intent, spans, "feedback", ner_missing=missing) for _ in range(repeat)
        )

    if seen:
        log(f"Поправок пользователя: {len(seen)} (в корпус — по {repeat} копий)")
    return examples


#: Намерения, у которых цель в фразе есть почти всегда. Если для такой фразы
#: границы восстановить не удалось — это «неизвестно», а не «цели нет».
_TARGET_INTENTS = {
    "open_app", "close_app", "open_folder", "open_url",
    "web_search", "scan_files", "timer", "remember", "math", "convert",
}

#: Метка цели по намерению — для случая, когда границы снимаются по глаголу.
_LABEL_BY_INTENT = {
    "open_app": "APP", "close_app": "APP", "open_folder": "FOLDER",
    "web_search": "QUERY", "scan_files": "QUERY",
}


def _strip_leading_verb(phrase: str, verbs: Sequence[str]):
    """
    Отрезает глагол в начале фразы и возвращает (смещение, остаток).

    Только в начале — сознательно. «Найди амонг ас» разбирается однозначно, а в
    «хочу открыть телеграм» глагол стоит не первым, порядок слов свободный, и
    угадывание здесь дало бы неверные границы. Неверная разметка вреднее
    отсутствующей, поэтому такие фразы уходят в «неизвестно».
    """
    lowered = phrase.lower()
    for verb in sorted(verbs, key=len, reverse=True):
        if lowered.startswith(verb + " "):
            offset = len(verb) + 1
            while offset < len(phrase) and phrase[offset] == " ":
                offset += 1
            return offset, phrase[offset:]
    return -1, ""


#: Слова, которые сами целью не бывают: «найди ИГРУ амонг ас».
_TAIL_NOISE = ("игру ", "игра ", "игры ", "игрушку ", "файл ", "файлы ", "программу ",
               "приложение ", "прогу ", "мне ", "в интернете ", "в гугле ", "в сети ",
               "в яндексе ", "информацию о ", "информацию про ", "инфу о ", "инфу про ",
               "в стиме ", "через стим ", "из стима ", "сайт ", "страницу ", "на сайт ")


def _align(phrase: str, intent: str, app_aliases: List[str], folder_aliases: List[str]):
    """
    Границы цели для фразы из brain.js: сначала словарь, потом глагол.

    :returns: (список границ, признак «границы неизвестны»)
    """
    lowered = phrase.lower()

    def unknown():
        return [], intent in _TARGET_INTENTS

    if intent == "open_url":
        match = _URL_RE.search(phrase)
        return ([(match.start(), match.end(), "URL")], False) if match else unknown()

    if intent == "open_folder":
        match = _PATH_RE.search(phrase)
        if match:
            return [(match.start(), match.end(), "PATH")], False
        for alias in folder_aliases:
            position = lowered.find(alias)
            if position >= 0:
                return [(position, position + len(alias), "FOLDER")], False

    if intent in ("open_app", "close_app"):
        for alias in app_aliases:
            position = lowered.find(alias)
            if position >= 0:
                return [(position, position + len(alias), "APP")], False

    # Словарь не помог. Пробуем снять глагол — так же, как это делает nlu.js.
    label = _LABEL_BY_INTENT.get(intent)
    if label:
        lex = load_lexicon()
        verbs = {
            "open_app": lex.open_verbs + ["открой", "запусти", "включи"],
            "close_app": lex.close_verbs,
            "open_folder": lex.open_verbs + ["покажи", "зайди", "перейди"],
            "web_search": lex.search_verbs + lex.scan_verbs,
            "scan_files": lex.scan_verbs,
        }[intent]

        offset, rest = _strip_leading_verb(phrase, verbs)
        if offset > 0 and rest:
            # «найди игру амонг ас» → цель «амонг ас», а не «игру амонг ас»
            changed = True
            while changed:
                changed = False
                for noise in _TAIL_NOISE:
                    if rest.lower().startswith(noise):
                        offset += len(noise)
                        rest = rest[len(noise):]
                        changed = True
            rest = rest.rstrip(" .,!?;:")
            if len(rest) >= 2:
                return [(offset, offset + len(rest), label)], False

    return unknown()


def _fillers_for(label: str, lex) -> List[str]:
    if label == "APP":
        return [alias for aliases in lex.app_aliases.values() for alias in aliases] + APPS_FREE
    if label == "FOLDER_NAMED":
        return [alias for aliases in lex.folder_aliases.values() for alias in aliases]
    if label == "FOLDER":
        named = [alias for aliases in lex.folder_aliases.values() for alias in aliases]
        return named + FOLDERS_FREE
    if label == "SITE":
        return [alias for aliases in lex.site_aliases.values() for alias in aliases]
    if label == "PATH":
        return list(PATHS)
    if label == "URL":
        return list(URLS)
    return []


def _queries_for(intent: str) -> List[str]:
    if intent == "scan_files":
        return list(SCAN_QUERIES)
    if intent == "web_search":
        return list(WEB_QUERIES)
    if intent == "volume_set":
        return list(VOLUME_LEVELS)
    return list(SLOT_SOURCES.get(intent, []))


def _split_holdout(values: List[str], ratio: float, rng: random.Random) -> Tuple[List[str], List[str]]:
    """Делит список на «для обучения» и «только для проверки»."""
    pool = list(values)
    rng.shuffle(pool)
    cut = max(1, int(len(pool) * ratio)) if len(pool) > 4 else 0
    return pool[cut:], pool[:cut]


def generate(rng: random.Random, per_template: int = 14, holdout: float = 0.15):
    """
    Порождает фразы по шаблонам, откладывая часть данных на проверку.

    Что именно откладывать — вопрос, на который у корпуса есть один правильный
    ответ, и первый вариант был неправильным. Тогда откладывались ШАБЛОНЫ, и
    выглядело это честно: сеть проверяется на оборотах, которых не видела. На
    деле получилось иначе — в проверку целиком ушёл шаблон «включай {}», и все
    четырнадцать ошибок «открытие вместо закрытия» оказались одной и той же
    фразой: модель впервые встречала слово «включай», а рядом были знакомые
    «выключи» и «вырубай». Это не провал обобщения, это отсутствие слова в
    словаре.

    Разница принципиальная. Глаголы — закрытое множество из полутора десятков
    слов, и оно ПЕРЕЧИСЛЕНО в nlu.js: научить модель всем синонимам «открой» не
    поддавки, а прямая задача. Названия программ, папок и поисковые запросы —
    множество открытое, никаким списком не исчерпывается, и вот на них проверять
    надо обязательно.

    Поэтому теперь: у фраз со слотом в обучение идут ВСЕ шаблоны, а откладываются
    значения — проверочная фраза собрана из знакомого оборота и незнакомого
    названия. У фраз без слота («сделай тише», «что ты умеешь») формулировка сама
    и есть открытая часть, там по-прежнему откладываются обороты.
    """
    lex = load_lexicon()
    train: List[Example] = []
    dev: List[Example] = []

    for intent, templates in TEMPLATES.items():
        free_form = [t for t in templates if t[1] is None]
        train_phrasings, dev_phrasings = _split_holdout(
            [t[0] for t in free_form], holdout, rng
        )
        dev_phrasing_set = set(dev_phrasings)

        for template, label in templates:
            # --- фразы без слота: откладываем формулировки -------------------
            if label is None:
                values = _queries_for(intent)
                if "{}" in template and values:
                    # Фраза целиком приходит из списка значений (denied,
                    # smalltalk): шаблон один, делить по шаблонам нечего.
                    train_values, dev_values = _split_holdout(values, holdout, rng)
                    for value in train_values:
                        train.append(Example(template.format(value), intent, []))
                    for value in dev_values:
                        dev.append(Example(template.format(value), intent, []))
                else:
                    target = dev if template in dev_phrasing_set else train
                    for _ in range(max(2, per_template // 3)):
                        target.append(Example(template, intent, []))
                continue

            # --- фразы со слотом: откладываем значения -----------------------
            values = _queries_for(intent) if label == "QUERY" else _fillers_for(label, lex)
            if not values:
                continue
            train_values, dev_values = _split_holdout(values, holdout, rng)
            if not train_values:
                continue

            prefix, suffix = template.split("{}")

            def emit(pool: List[str], count: int, target: List[Example]) -> None:
                for _ in range(count):
                    value = rng.choice(pool)
                    if label in ("FOLDER", "FOLDER_NAMED", "QUERY") and rng.random() < 0.25 and " " not in value:
                        variants = case_variants(value)
                        if variants:
                            value = rng.choice(variants)
                    text = prefix + value + suffix
                    # FOLDER_NAMED — ограничение на подстановку, а не отдельная
                    # метка: разметчик должен знать про папки одну сущность.
                    emitted = "FOLDER" if label == "FOLDER_NAMED" else label
                    target.append(Example(text, intent, [(len(prefix), len(prefix) + len(value), emitted)]))

            emit(train_values, per_template, train)
            if dev_values:
                emit(dev_values, max(1, per_template // 5), dev)

    return train, dev


def build(
    out_dir: str = "data/nlu",
    per_template: int = 14,
    augment_factor: int = 3,
    seed: int = 20260808,
) -> dict:
    """Собирает корпус и кладёт рядом .jsonl для чтения глазами."""
    rng = random.Random(seed)

    seed_examples = harvest_brain()
    generated_train, generated_dev = generate(rng, per_template=per_template)

    # Фразы из brain.js делим обычным способом: они настоящие, и держать их
    # целиком в обучении — значит остаться без честной проверки на живой речи.
    rng.shuffle(seed_examples)
    cut = int(len(seed_examples) * 0.85)
    train = seed_examples[:cut] + generated_train
    dev = seed_examples[cut:] + generated_dev

    # Поправки идут только в обучение. Класть их в проверку нельзя: это фразы,
    # на которых модель уже ошиблась, и отчёт по ним говорил бы не о качестве,
    # а о том, сколько раз пользователь нажал «Не угадал?».
    train += harvest_feedback(Path(out_dir) / "feedback.jsonl")

    augmented: List[Example] = []
    for example in train:
        augmented.append(example)
        for _ in range(augment_factor):
            augmented.append(augment(example, rng))
    train = augmented

    # Проверочные фразы тоже слегка портим — но однократно: пользователь
    # опечатывается и в тех запросах, которых сеть не видела.
    dev = [example if rng.random() < 0.5 else augment(example, rng) for example in dev]

    rng.shuffle(train)
    rng.shuffle(dev)

    path = Path(out_dir)
    path.mkdir(parents=True, exist_ok=True)
    _dump(path / "train.jsonl", train)
    _dump(path / "dev.jsonl", dev)

    stats = {
        "train": len(train),
        "dev": len(dev),
        "intents": len(load_lexicon().intents),
        "spans_train": sum(len(e.spans) for e in train),
        "spans_dev": sum(len(e.spans) for e in dev),
        "seed": seed,
    }
    (path / "stats.json").write_text(json.dumps(stats, ensure_ascii=False, indent=2), encoding="utf-8")

    log(f"Обучающих фраз: {stats['train']} · проверочных: {stats['dev']}")
    log(f"Размеченных целей: {stats['spans_train']} в обучении, {stats['spans_dev']} в проверке")
    log(f"Корпус записан в {path}")
    return stats


def _dump(path: Path, examples: Iterable[Example]) -> None:
    with path.open("w", encoding="utf-8") as handle:
        for example in examples:
            handle.write(json.dumps(example.as_json(), ensure_ascii=False) + "\n")


def read(path: Path) -> List[Example]:
    examples = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        record = json.loads(line)
        examples.append(Example(
            text=record["text"],
            intent=record["intent"],
            spans=[(s, e, label) for s, e, label in record["spans"]],
            origin=record.get("origin", "template"),
            ner_missing=bool(record.get("ner_missing", False)),
        ))
    return examples

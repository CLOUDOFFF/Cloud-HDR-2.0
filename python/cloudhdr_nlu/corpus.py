def _shift(spans: Sequence[Tuple[int, int, str]], position: int, delta: int) -> List[Tuple[int, int, str]]:
    """Сдвигает границы после правки текста в точке `position`."""
    moved = []
    for start, end, label in spans:
        if delta > 0:                       # вставка
            if position <= start:
                start += delta
            if position < end:
                end += delta
        else:                               # удаление
            if position < start:
                start += delta
            if position < end:
                end += delta
        if end > start:
            moved.append((start, end, label))
    return moved



"""
Сборка обучающего корпуса: намерение + границы цели команды.

Откуда берутся данные.

  1. 603 размеченные фразы из brain.js. Это настоящие формулировки, ради них
     всё и затевалось, но для нейросети их мало на порядок, и границ цели
     («что именно открыть») в них нет — только метка намерения.

  2. Порождение по шаблонам. Шаблон «{verb} {app}» с сотней значений в каждом
     слоте даёт тысячи фраз, и, что важнее, границы цели известны точно: мы
     сами подставили значение и знаем, с какого символа оно начинается. Ради
     этого шаблоны и нужны — размечать спаны руками по 603 фразам было бы и
     дольше, и менее точно.

  3. Аугментация: опечатки, регистр, слова-паразиты, падежи через pymorphy3.
     Пользователь пишет «врубай дискордик пж», а не «Запустить Discord».

Как делится выборка — отдельный вопрос, и случайным перемешиванием он не
решается: тогда на проверке оказались бы те же «открой дискорд» с другой
опечаткой, точность вышла бы под сотню и не значила бы ничего. Откладывается
ОТКРЫТАЯ часть данных — названия программ, папок, поисковые запросы: их
множество ничем не исчерпывается, и обобщать модель должна именно на них.
Подробно, вместе с историей одной ошибки в этом разделении, — в generate().
"""


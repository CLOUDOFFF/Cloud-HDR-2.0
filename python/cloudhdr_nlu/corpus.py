#: Метки цели команды. Их намеренно мало: чем меньше классов, тем увереннее
#: разметчик на объёмах, которые мы можем породить.
SLOT_LABELS = ("APP", "FOLDER", "PATH", "URL", "SITE", "QUERY")


@dataclass
class Example:
    text: str
    intent: str
    spans: List[Tuple[int, int, str]] = field(default_factory=list)
    origin: str = "template"

    #: «Границы цели неизвестны» — не то же самое, что «цели нет».
    #:
    #: Разница вышла дорогой. Пустой список spaCy понимает однозначно: в этой
    #: фразе цели НЕТ, все токены снаружи. Для «привет» или «сделай тише» это
    #: правда. Но у фраз из brain.js границы просто не размечены, и когда словарь
    #: не смог их восстановить, каждая такая фраза учила разметчик, что цели в
    #: ней нет. Проверка это и показала: «открой фотошоп», «загугли рецепт
    #: борща», «найди игру амонг ас» — все три есть в brain.js дословно, и на всех
    #: трёх сеть не выделяла ничего, хотя «найди амонг ас» разбирала верно.
    #:
    #: С этим флагом токены помечаются как неизвестные: намерению они учат,
    #: разметчику границ — не мешают.
    ner_missing: bool = False

    def as_json(self) -> dict:
        return {
            "text": self.text,
            "intent": self.intent,
            "spans": [[s, e, label] for s, e, label in self.spans],
            "origin": self.origin,
            "ner_missing": self.ner_missing,
        }



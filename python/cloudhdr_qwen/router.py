SCHEMA = {
    'type': 'object',
    'properties': {
        'commands': {'type': 'array', 'items': {'type': 'string', 'maxLength': 160}, 'maxItems': 5},
        'ask': {'type': 'string', 'maxLength': 200},
        'say': {'type': 'string', 'maxLength': 200},
    },
    'required': ['commands', 'ask', 'say'],
}


def build_messages(text: str, history: list | None = None) -> list:
    """history — предыдущие реплики уточнения: [{role, content}, …]."""
    messages = [{'role': 'system', 'content': SYSTEM}]
    for turn in (history or [])[-4:]:
        if isinstance(turn, dict) and turn.get('role') in ('user', 'assistant') and turn.get('content'):
            messages.append({'role': turn['role'], 'content': str(turn['content'])[:500]})
    messages.append({'role': 'user', 'content': text[:500]})
    return messages


def clean(result: dict, text: str) -> dict:
    """Отбросить то, что модель всё-таки сделала не по правилам."""
    commands = [c for c in result.get('commands', []) if '<' not in c and '>' not in c]
    ask = result.get('ask', '')
    low = lambda v: ''.join(ch for ch in v.lower() if ch.isalnum())  # noqa: E731
    if ask and (low(ask) in low(text) or low(text) in low(ask)):
        ask = ''                       # повторила просьбу вместо вопроса
    if commands:
        ask = ''                       # есть что делать — не переспрашиваем
    return {'commands': commands, 'ask': ask, 'say': result.get('say', '') if commands else ''}

def clean(result: dict) -> dict:
    action = str(result.get('action') or '')
    if action not in ACTIONS:
        action = 'ask'
    try:
        ident = int(result.get('id') or 0)
    except (TypeError, ValueError):
        ident = 0
    return {'why': str(result.get('why') or '').strip(), 'action': action, 'id': ident,
            'text': str(result.get('text') or '').strip(), 'say': str(result.get('say') or '').strip()}


# ------------------------------------------------------------- план целиком --
#
# Маленькой модели тяжело держать в голове длинную просьбу и одновременно
# выбирать элементы на экране: она теряет нить и ходит кругами. Поэтому сначала
# просьба режется на короткие подзадачи — каждая либо «открой …» (выполняется
# сразу, без экрана), либо одно простое действие на экране, которое модель
# потом доводит по шагам.

PLAN_SYSTEM = """Ты разбиваешь просьбу пользователя к компьютеру на короткие подзадачи для рук помощника Cloud HDR.
Каждая подзадача — одно простое действие. Их два вида:
1) «открой <что>» — программа, папка, файл, раздел настроек или сайт адресом. Это выполняется сразу.
   Поиск на сайтах — одной ссылкой:
   YouTube → открой youtube.com/results?search_query=<запрос>
   Яндекс Музыка → открой music.yandex.ru/search?text=<запрос>
   интернет → открой ya.ru/search/?text=<запрос>
   Сайты по названию: ютуб → youtube.com, вк → vk.com, яндекс → ya.ru, кинопоиск → kinopoisk.ru, озон → ozon.ru.
2) действие на экране: «нажми <что>», «напечатай <текст> в <поле>», «прокрути вниз», «нажми клавишу <клавиша>».
   «Нажми клавишу» — только для настоящих клавиш: enter, esc, space, ctrl+s. Кнопки на экране («Пауза», «Подписаться») — «нажми «<кнопка>»».
   Если нужное в другом окне — сначала «перейди в окно <название>».
Не больше 6 подзадач. Не добавляй того, о чём не просили.
Если просят удалить, купить, отправить сообщение или выключить компьютер — верни пустой список и вопрос в "ask".
В "say" — одна короткая фраза, что сделаешь."""

PLAN_EXAMPLES = [
    ('открой ютуб, найди видео про котов и включи первое',
     {'steps': ['открой youtube.com/results?search_query=видео про котов', 'нажми на первое видео в результатах'],
      'ask': '', 'say': 'Ищу видео про котов на YouTube.'}),
    ('зайди в вк и открой сообщения',
     {'steps': ['открой vk.com', 'нажми «Мессенджер»'], 'ask': '', 'say': 'Открываю сообщения ВКонтакте.'}),
    ('открой блокнот и напиши привет мир',
     {'steps': ['открой блокнот', 'напечатай «привет мир» в поле текста'], 'ask': '', 'say': 'Пишу в блокноте.'}),
    ('включи в настройках тёмную тему',
     {'steps': ['открой настройки цвета', 'нажми на список «Выберите режим»', 'нажми «Тёмный»'], 'ask': '',
      'say': 'Включаю тёмную тему.'}),
]

PLAN_SCHEMA = {
    'type': 'object',
    'properties': {
        'steps': {'type': 'array', 'items': {'type': 'string', 'maxLength': 200}, 'maxItems': 6},
        'ask': {'type': 'string', 'maxLength': 200},
        'say': {'type': 'string', 'maxLength': 200},
    },
    'required': ['steps', 'ask', 'say'],
}


def build_plan_messages(goal: str, screen: str = '') -> list:
    import json
    messages = [{'role': 'system', 'content': PLAN_SYSTEM}]
    for text, answer in PLAN_EXAMPLES:
        messages.append({'role': 'user', 'content': text})
        messages.append({'role': 'assistant', 'content': json.dumps(answer, ensure_ascii=False)})
    # Пример с окнами: нужное уже открыто, но не впереди — сначала перейти.
    messages.append({'role': 'user', 'content': 'поставь музыку на паузу\n\nСейчас на экране:\nОкно впереди: «Параметры»\n'
                                                 'Открытые окна: «Параметры», «Яндекс Музыка»'})
    messages.append({'role': 'assistant', 'content': json.dumps(
        {'steps': ['перейди в окно «Яндекс Музыка»', 'нажми «Пауза»'], 'ask': '', 'say': 'Ставлю на паузу.'},
        ensure_ascii=False)})
    tail = f'\n\nСейчас на экране:\n{screen[:700]}' if screen else ''
    messages.append({'role': 'user', 'content': goal[:400] + tail})
    return messages


def clean_plan(result: dict) -> dict:
    steps = [str(s).strip() for s in (result.get('steps') or []) if str(s).strip() and '<' not in str(s)][:6]
    return {'steps': steps, 'ask': '' if steps else str(result.get('ask') or '').strip(),
            'say': str(result.get('say') or '').strip()}

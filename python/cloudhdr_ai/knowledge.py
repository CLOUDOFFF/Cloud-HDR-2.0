"""
Cloud HDR AI — справка из Википедии для ответов модели.

Зачем это вообще нужно. Худший дефект маленькой языковой модели не в том, что
она чего-то не знает, — а в том, что она этого не замечает. На «что такое сила
тяжести» она уверенно выдаёт формулу «m = m · cos(πt)», а инфляцию объясняет как
«когда цены растут быстрее инфляции». Звучит гладко, читается как определение и
является выдумкой. Никакое дообучение это не лечит: факты о мире физически не
помещаются в 760 млн параметров, и модель всегда будет заполнять пробел
правдоподобным текстом.

Лечится это иначе — не памятью модели, а подсказкой. Перед ответом мы находим
статью в Википедии и кладём её начало прямо в контекст, рядом с вопросом. Модели
больше не нужно вспоминать — ответ у неё перед глазами, её работа сводится к
пересказу. Это и есть весь приём, и он работает тем лучше, чем меньше модель.

Три решения, которые определяют, помогает эта справка или мешает.

СПРАВКА ТОЛЬКО ТАМ, ГДЕ ОНА УМЕСТНА. На «привет» и «что ты умеешь» Википедия не
нужна: своё имя и свои возможности модель знает из обучения, а подставленная
статья про приветствие сбила бы её с толку. Поэтому запрос уходит в сеть, только
если реплика похожа на вопрос о мире.

СЕТЬ НЕ ДОЛЖНА ВЕШАТЬ РАЗГОВОР. Википедия — единственное место в проекте, куда
уходит запрос наружу, и она может не ответить: нет интернета, лежит сеть, статьи
не существует. Любая такая беда означает ровно одно — отвечаем без справки, как
раньше. Ошибка поиска не имеет права превратиться в ошибку чата.

ПОВТОРЫ НЕ ХОДЯТ В СЕТЬ. Один и тот же предмет в разговоре всплывает не раз
(«кто такой Гагарин» → «а когда он летал»), и каждый поход за той же статьёй
добавлял бы к ответу лишние полсекунды. Небольшой кеш в памяти процесса это
снимает.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import Optional

from .branding import log

#: Местоимения, по которым видно, что вопрос о собеседниках, а не о мире.
#:
#: Проверяются НЕ во всей фразе, а в предмете, который выделил topic_of, — и в
#: этом весь смысл. Сравните, что он выделяет:
#:
#:     «что ты умеешь»            → «ты умеешь»      ← предмет и есть собеседник
#:     «расскажи о себе»          → «себе»           ← то же
#:     «как меня зовут»           → «меня зовут»     ← вопрос о пользователе
#:     «что ты знаешь о Байкале»  → «Байкале»        ← а вот здесь предмет внешний
#:
#: Проверка по всей фразе зарубила бы последний случай вместе с первыми, хотя
#: справка там как раз нужна. Проверка по предмету различает их сама.
#:
#: Без этого фильтра «что ты умеешь» уходило в Википедию и находило статью
#: «Ты умеешь хранить секреты? (фильм)» — модель получала подсказку про кино и
#: отвечала по ней вместо рассказа о своих возможностях.
#: Вопросы, на которые статья Википедии действительно отвечает.
#:
#: Список белый, а не чёрный, и это выяснилось дорогой ценой. Сначала справка
#: подставлялась всюду, где текст похож на вопрос, — и вот что вышло на прогоне:
#:
#:     «почему нужно спать восемь ЧАСОВ?»  → статья «Часов Яр», город в Донецкой
#:                                            области — предмет вопроса у «почему»
#:                                            берётся по последнему слову
#:     «чем отличается ОЗУ от ЖЁСТКОГО ДИСКА?» → «Внешний жёсткий диск», то есть
#:                                            ответ про одну сторону сравнения
#:
#: Общее у промахов одно: справка хороша, когда спрашивают «что это такое», и
#: бесполезна, когда спрашивают «почему так» или «чем одно отличается от
#: другого». В первом случае предмет назван прямо и статья про него и есть
#: ответ. Во втором ответа в одной статье нет в принципе — и лучше пусть
#: отвечает модель своими словами, пусть и не идеально.
_DEFINITION_QUESTION = re.compile(
    r"^\s*(кто\s+так(ой|ая|ие|ое)|что\s+так(ое|ая)|что\s+за\b|"
    r"расскажи\s+(мне\s+)?(о|про)\b|что\s+значит\b|кто\s+это\b)",
    re.IGNORECASE,
)

#: Сравнения и противопоставления — им одна статья не поможет никогда.
_COMPARISON = re.compile(
    r"(отлича\w+|разниц\w+|отличи\w+|чем\s+лучше|что\s+лучше|"
    r"вместо|сравн\w+|\bили\b|\bлибо\b)",
    re.IGNORECASE,
)

_SELF_TOPIC = re.compile(
    r"\b(ты|тебя|тебе|тобой|тво[йяёеиюм]\w*|себе|себя|собой|"
    r"я|меня|мне|мной|мо[йяёеиюм]\w*|нас|нам|наш\w*)\b",
    re.IGNORECASE,
)

#: Сколько знаков статьи класть в подсказку.
#:
#: Не больше: у модели контекст 2048 токенов, и справка в две тысячи знаков
#: съела бы заметную его часть, вытеснив сам разговор. Не меньше: первые
#: полтораста знаков статьи — это обычно одно определение без единого факта,
#: пересказывать там нечего.
EXTRACT_LIMIT = 700

#: Сколько статей помнить, чтобы не ходить в сеть дважды за одним и тем же.
CACHE_SIZE = 64

_cache: dict = {}
_wiki = None
_wiki_failed = False


def _module():
    """
    Подключает cloudhdr_wiki — он лежит рядом с пакетом, а не внутри него.

    Импорт отложенный и одноразовый: при работе без сети модуля может не быть
    вовсе, и разваливать из-за этого запуск сервера незачем.
    """
    global _wiki, _wiki_failed
    if _wiki is not None or _wiki_failed:
        return _wiki

    root = Path(__file__).resolve().parents[1]      # …/python
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))
    try:
        import cloudhdr_wiki                        # noqa: PLC0415
        _wiki = cloudhdr_wiki
    except Exception as error:                      # noqa: BLE001
        log(f"Справка из Википедии недоступна: {error}")
        _wiki_failed = True
    return _wiki


def lookup(question: str) -> Optional[dict]:
    """
    Ищет статью по вопросу и возвращает {"title", "extract", "url"} либо None.

    None означает «отвечай сам»: не вопрос о мире, нет статьи, нет сети.
    Различать эти случаи вызывающему не нужно — поведение во всех одинаковое.
    """
    wiki = _module()
    if wiki is None or not question:
        return None

    try:
        if not _DEFINITION_QUESTION.match(question) or _COMPARISON.search(question):
            return None

        topic = wiki.topic_of(question)
        if len(topic) < 2:
            return None

        # Вопрос о самой модели, о пользователе или о его компьютере: в
        # Википедии такого нет, а случайно найденная статья только помешает.
        if _SELF_TOPIC.search(topic):
            return None

        key = topic.lower()
        if key in _cache:
            return _cache[key]

        title = wiki.find_title(topic)
        extract = wiki.summary(title) if title else None
        if not (title and extract):
            _cache[key] = None                      # запоминаем и промах
            return None

        # Обрезаем по границе предложения: оборванная на полуслове справка учит
        # модель обрывать и свой ответ.
        text = extract.strip()
        if len(text) > EXTRACT_LIMIT:
            cut = text.rfind(". ", 0, EXTRACT_LIMIT)
            text = text[: cut + 1] if cut > 200 else text[:EXTRACT_LIMIT]

        found = {
            "title": title,
            "extract": text,
            "url": "https://ru.wikipedia.org/wiki/" + title.replace(" ", "_"),
        }

        if len(_cache) >= CACHE_SIZE:
            _cache.clear()
        _cache[key] = found
        return found

    except Exception as error:                      # noqa: BLE001
        # Сеть отвалилась, Википедия ответила мусором, поменялся формат — что бы
        # ни случилось, разговор продолжается без справки.
        log(f"Справка не получена ({type(error).__name__}) — отвечаю без неё")
        return None


#: Зачины, чтобы ответы не звучали как автоответчик.
_OPENERS = (
    "{}", "Коротко: {}", "Если кратко — {}", "Вот что известно: {}",
)


def direct_answer(found: dict, seed: Optional[int] = None) -> str:
    """
    Отдаёт факт из статьи ДОСЛОВНО, без пересказа моделью.

    Почему не пересказ. Сначала справка отдавалась модели как контекст, и та
    отвечала своими словами — так задумывалось и так делают большие модели.
    Замер показал, что на 356M и 760M это не работает: суть модель схватывает, а имена
    и числа переписывает своими. Гагарин из статьи выходил «(1907–1968),
    первым ступившим на поверхность Луны», Асхаб Тамаев получал выдуманную
    фамилию «Тамазов» и дату рождения, которой в справке нет. Понижение
    температуры до 0.2 не помогло — стало хуже.

    Причина не в настройках. Имена и даты — редкие токены, и на каждом из них
    модель выбирает из нескольких похожих, опираясь на то, что видела при
    обучении, а не на то, что лежит перед ней. Чем меньше модель, тем сильнее
    её собственные привычки перебивают контекст.

    Поэтому факт возвращается дословно. Это честнее: лучше точная цитата, чем
    гладкий пересказ с переставленными датами, который читается убедительнее
    правды. Модель остаётся на том, что умеет, — на разговоре.
    """
    import random

    wiki = _module()
    idea = wiki.main_idea(found["extract"], sentences=2, limit=420) if wiki else None
    text = idea or found["extract"][:420]

    rng = random.Random(seed if seed is not None else hash(found["title"]) & 0xFFFF)
    return rng.choice(_OPENERS).format(text) + f"\n\nИсточник: Википедия, «{found['title']}»."


def augment(system_prompt: str, found: dict) -> str:
    """
    Добавляет справку к системной подсказке.

    Кладётся именно в системную часть, а не отдельной репликой: модель обучена
    видеть в этой позиции указания к работе, и справка воспринимается как
    указание, а не как чьи-то слова в разговоре.

    Отдельно сказано, что делать, если в справке ответа нет. Без этой строки
    модель, не найдя нужного, всё равно сочиняет — теперь уже на основе
    подставленного текста, и выходит правдоподобнее и потому хуже.
    """
    return (
        f"{system_prompt}\n\n"
        f"Справка из Википедии, статья «{found['title']}»:\n"
        f"{found['extract']}\n\n"
        "Ответь на вопрос пользователя, опираясь на эту справку и своими словами. "
        "Не добавляй того, чего в ней нет. Если ответа в справке нет — так и скажи."
    )

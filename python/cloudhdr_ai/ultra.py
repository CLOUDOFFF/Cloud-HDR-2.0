#: Как просят стихи.
#:
#: Две разные формы, и разделены они не для красоты, а из-за падежей.
#:
#: Ключевые слова в наборе лежат в начальной форме: «снег», «дорога», «рыть».
#: Подставить такое в «стихотворение про {}» нельзя — выходит «про рыть» и «про
#: пища». Учить модель на неграмотных просьбах вредно вдвойне: она и сама
#: начнёт так писать, и перестанет узнавать правильную форму вопроса.
#:
#: Поэтому основная форма — перечисление слов после двоеточия, где начальная
#: форма и уместна. А «про {}» остаётся, но только для слов, которые в
#: именительном падеже и стоят (см. _NOUN_LIKE): без него корпус состоял бы из
#: одних канцелярских «ключевые слова:», и живой вопрос «напиши стих про осень»
#: оказался бы для модели незнакомым.
_VERSE_ASKS_WORDS = (
    "сочини стихотворение. слова: {}",
    "напиши стихи, ключевые слова: {}",
    "сочини стихотворение на тему: {}",
    "напиши стихотворение, используй слова: {}",
    "нужны стихи. слова: {}",
)

_VERSE_ASKS_TOPIC = (
    "сочини стихотворение про {}",
    "напиши стих о {}",
    "сочини стихи про {}",
    "нужно стихотворение про {}",
    "напиши что-нибудь в рифму про {}",
)

#: Запасной набор — на случай, когда до Hugging Face не достучаться.
#:
#: Восемь стихотворений корпусом не назовёшь, и рифмовать по ним модель не
#: научится. Задача у них другая и достижимая: показать ФОРМУ ответа — строки в
#: столбик, без вводных слов и без объяснения замысла. Рифмовать болванка
#: rugpt3 умеет и так, ей мешало только то, что на просьбу о стихах она отвечала
#: прозой.
_FALLBACK_VERSE = [
    ("зима", "Метель улеглась к четырём,\nи двор побелел до крыльца.\nМы чай на веранде допьём —\nзима не имеет конца.\n\nА к марту, глядишь, потечёт\nс железа холодная нить,\nи снова пойдёт этот счёт:\nдожить, досидеть, долюбить."),
    ("город", "Гудят провода над двором,\nи город стоит на ветру.\nОн будет и завтра, и в том,\nчто я поутру не умру.\n\nОкно за окном, этаж\nсчитает свои огни.\nИ этот бессонный мираж\nмне ближе, чем все они."),
    ("море", "У моря нет ни дна, ни дела,\nоно качается и ждёт.\nВолна к ногам подкатит смело\nи так же смело отойдёт.\n\nА мы стоим, считая пену,\nи каждый думает своё:\nчто эта тихая измена\nи есть спокойствие твоё."),
    ("осень", "Сентябрь заходит без стука,\nкладёт на подушку листву.\nИ это не грусть, а наука —\nсмотреть, как я молча живу.\n\nДень стал короче на треть,\nи чай остывает быстрей.\nНо есть на что посмотреть\nв последних тёплых дверей."),
    ("кот", "Кот занимает окно,\nкак занимают престол.\nЕму совершенно равно,\nчто я наконец подмёл.\n\nОн смотрит сквозь стёкла в сад,\nгде птицы и снегопад,\nи держит на мне взгляд\nтак, будто я виноват."),
    ("дорога", "Дорога уходит в туман,\nи фары не держат черты.\nИ карта — почти обман,\nи всё-таки едешь ты.\n\nПотом рассветёт, и поля\nоткроются справа и слева.\nИ станет понятно: земля\nкруглая, как и было дело."),
    ("работа", "С утра загорается свет\nв конторе на пятом этаже.\nИ кажется, выхода нет,\nа выход-то найден уже.\n\nОн в том, чтобы к шести\nзакрыть за собою дверь\nи медленно вниз сойти,\nи в лифте себе поверить."),
    ("звёзды", "Над крышей висят вразброс\nдалёкие фонари.\nИ каждый из них — вопрос,\nна который молчи и смотри.\n\nОни горели до нас,\nи будут гореть потом.\nИ этот холодный час\nмы всё-таки проживём."),
]


def _clean_poem(text: str, max_lines: int, max_chars: int) -> Optional[str]:
    """Приводит стихотворение к виду, годному для обучающего примера."""
    lines = [line.strip() for line in str(text).replace("\r", "").split("\n")]

    # Пустые строки внутри — это разделение на строфы, и они нужны; подряд
    # идущие схлопываем, ведущие и хвостовые убираем.
    cleaned: List[str] = []
    for line in lines:
        if not line and (not cleaned or not cleaned[-1]):
            continue
        cleaned.append(line)
    while cleaned and not cleaned[-1]:
        cleaned.pop()

    if len(cleaned) < 4:
        return None
    cleaned = cleaned[:max_lines]
    while cleaned and not cleaned[-1]:
        cleaned.pop()

    poem = "\n".join(cleaned)
    if len(poem) > max_chars or len(poem) < 60:
        return None

    # Отбраковка прозы. В наборе попадаются записи, где стихотворение слито в
    # сплошной абзац: переводы строк потерялись при сборе. Внешне это стихи, для
    # обучения — образец того, как отвечать на просьбу о стихах абзацем текста.
    # Признак простой и надёжный: у стихотворной строки есть предел длины.
    body = [line for line in cleaned if line]
    if sum(1 for line in body if len(line) > 90) > len(body) / 4:
        return None
    return poem


#: Слово темы из ключевых слов набора. Годится не всякое: служебные части речи
#: темой быть не могут, а именно они чаще всего и оказываются частотными.
_BAD_TOPIC = re.compile(r"^(не|и|а|но|же|бы|ли|что|как|где|когда|это|весь|свой|мой|твой|его|её|их)$",
                        re.IGNORECASE)


#: Слово, которое не стыдно поставить после «про».
#:
#: Отсекаются глаголы (инфинитив на -ть/-ти/-чь и возвратные на -ся) и наречия
#: на -о: «про рыть», «про недоесть», «про быстро» — это не темы. Существительное
#: в именительном падеже после «про» формально тоже требует винительного, но у
#: неодушевлённых они совпадают, а именно такие в ключевых словах и преобладают.
#: Гласные «а» и «я» на конце отсекаются отдельно: у таких слов винительный
#: падеж отличается от именительного («пища» → «про пищу»), и подстановка даёт
#: «про пища». У всего остального — согласная, мягкий знак, «о», «е», множественное
#: число — формы совпадают, и «про ночь», «про счёты», «про небо» верны как есть.
_NOUN_LIKE = re.compile(
    r"^(?!.*(?:ться|тся)$)(?!.*(?:ть|ти|чь)$)(?!.*[ая]$)[а-яё]{4,}$",
    re.IGNORECASE,
)


def _topics_from(keywords: Any) -> List[str]:
    """Достаёт ключевые слова — поле приходит строкой вида "['снег', ...]"."""
    if isinstance(keywords, list):
        words = [str(word) for word in keywords]
    else:
        words = re.findall(r"'([^']+)'", str(keywords or ""))

    picked: List[str] = []
    for word in words:
        word = word.strip().lower()
        if len(word) >= 4 and not _BAD_TOPIC.match(word) and word not in picked:
            picked.append(word)
    return picked[:3]


def verse_dialogues(limit: int, seed: int, max_lines: int = 16,
                    max_chars: int = 700) -> List[List[Dict[str, str]]]:
    """Стихи с Hugging Face; если сети нет — запасной набор."""
    rng = random.Random(seed)
    rows: List[List[Dict[str, str]]] = []

    pairs: List[tuple] = []
    try:
        from datasets import load_dataset                       # noqa: PLC0415

        log("Стихи: качаю AnyaSchen/russian_poetry_with_keywords…")
        stream = load_dataset("AnyaSchen/russian_poetry_with_keywords",
                              split="train", streaming=True)

        # Берём не первые подряд, а прореженно по всему набору.
        #
        # Набор сложен по авторам: сначала весь Маяковский, потом весь Блок и так
        # далее. Взяв первую тысячу годных записей, мы получили бы корпус из
        # одного поэта — и модель выучила бы не «как пишут стихи», а «как пишет
        # Маяковский»: лесенкой, без рифмы и с его словарём.
        #
        # Отсюда и потолок в scan записей: пройти нужно заметно больше, чем взять.
        scan = max(limit * 12, 20000)
        seen_texts = set()
        collected: List[tuple] = []
        index = -1
        for index, record in enumerate(stream):
            if index >= scan:
                break
            topics = _topics_from(record.get("keywords"))
            poem = _clean_poem(record.get("text", ""), max_lines, max_chars)
            if not (topics and poem):
                continue
            key = poem[:80]
            if key in seen_texts:
                continue
            seen_texts.add(key)
            collected.append((topics, poem))

        rng.shuffle(collected)
        pairs = collected[:limit]
        log(f"Стихи: просмотрено {min(index + 1, scan)}, годных {len(collected)}, "
            f"взято {len(pairs)}")
    except Exception as error:                                  # noqa: BLE001
        # Нет сети, набор переехал, поменялись поля — что бы ни случилось,
        # сборка корпуса продолжается. Потерять стихи неприятно, потерять весь
        # корпус из-за стихов — глупо.
        log(f"Стихи: набор недоступен ({type(error).__name__}) — беру запасной")

    if not pairs:
        pairs = [([topic], poem) for topic, poem in _FALLBACK_VERSE]

    # Запасной набор мал, поэтому его повторяем: восемь примеров на тысячу
    # шагов обучения не заметит никто.
    fallback = [([topic], poem) for topic, poem in _FALLBACK_VERSE]
    while len(pairs) < min(limit, 120):
        pairs.extend(fallback)
    pairs = pairs[:limit]

    for topics, poem in pairs:
        head = topics[0]
        # Форма «про {}» — только там, где слово это выдержит грамматически.
        if _NOUN_LIKE.match(head) and rng.random() < 0.45:
            ask = rng.choice(_VERSE_ASKS_TOPIC).format(head)
        else:
            ask = rng.choice(_VERSE_ASKS_WORDS).format(", ".join(topics))

        if rng.random() < 0.3:
            ask = ask[0].upper() + ask[1:]
        rows.append([
            {"role": "system", "content": SYSTEM_VERSE},
            {"role": "user", "content": ask},
            {"role": "assistant", "content": poem},
        ])

    return rows


# ---------------------------------------------------------------- разговор --

def keep_dialogues(source: str, limit: int, seed: int) -> List[List[Dict[str, str]]]:
    """
    Выборка из прежнего корпуса — чтобы модель не разучилась разговаривать.

    Берётся случайно, а не первыми строками: корпус собирался по темам, и первые
    несколько тысяч строк — это несколько тем подряд, а не срез со всего.
    """
    path = Path(source)
    if not path.exists():
        log(f"Разговорный корпус не найден: {path} — обучение пойдёт без него")
        return []

    rng = random.Random(seed)
    rows: List[List[Dict[str, str]]] = []

    # Прореживание на лету: файл на сто мегабайт целиком в память класть незачем.
    with path.open(encoding="utf-8") as handle:
        total = sum(1 for _ in handle)
    share = min(1.0, (limit * 1.6) / max(total, 1))

    with path.open(encoding="utf-8") as handle:
        for line in handle:
            if len(rows) >= limit:
                break
            if rng.random() > share:
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                continue
            messages = record.get("messages")
            if isinstance(messages, list) and len(messages) >= 2:
                rows.append(messages)

    log(f"Разговор: взято {len(rows)} из {total}")
    return rows


# ------------------------------------------------------------------ сборка --

def build(out: str = "data/ultra.jsonl",
          source: str = "data/dialogues-v5.jsonl",
          code_repeat: int = 10,
          verse: int = 900,
          keep: int = 9000,
          seed: int = 20260819) -> Path:
    """Собирает корпус и кладёт его в файл."""
    rule("Корпус Cloud HDR Ultra")

    code = code_dialogues(code_repeat, seed)
    log(f"Код: {len(code)} примеров из {len(TASKS)} задач")

    poems = verse_dialogues(verse, seed + 1)
    log(f"Стихи: {len(poems)} примеров")

    talk = keep_dialogues(source, keep, seed + 2)

    rows = code + poems + talk
    random.Random(seed + 3).shuffle(rows)

    path = Path(out)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for messages in rows:
            handle.write(json.dumps({"messages": messages}, ensure_ascii=False) + "\n")

    rule()
    log(f"Готово: {path} — {len(rows)} диалогов "
        f"(код {len(code)}, стихи {len(poems)}, разговор {len(talk)})")
    log(f"Дальше: python -m cloudhdr_ai train --data {out} --resume checkpoints/v5/best.pt")
    return path

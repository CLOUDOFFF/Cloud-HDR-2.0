#: Как ещё можно попросить то же самое.
#:
#: Приставки подобраны так, чтобы вставать перед ЛЮБОЙ строкой банка, не ломая
#: согласование. «Можешь» и «мне нужно» отсюда убраны: они требуют инфинитива, а
#: в банке лежат и повелительные («напиши»), и вопросительные («как
#: отцентрировать») формулировки — выходило «можешь напиши» и «мне нужно как».
#: Пустая строка повторена трижды: большинство просьб пишут без вежливых
#: оборотов, и корпус должен это отражать.
_POLITE = ("", "", "", "пожалуйста, ", "слушай, ")

#: Хвосты — то, чем живая просьба отличается от строки из набора данных.
_TAILS = ("", "", "?", ".")

#: Благодарность в конце. Отдельно от _TAILS, потому что не сочетается с
#: «пожалуйста» в начале: «Пожалуйста, напиши … спасибо» — это не живая речь.
_THANKS = " спасибо"


def _vary_question(ask: str, rng: random.Random) -> str:
    """Одна и та же просьба, сказанная по-разному."""
    polite = rng.choice(_POLITE)
    text = polite + ask + rng.choice(_TAILS)
    if not polite and rng.random() < 0.12:
        text += _THANKS
    if rng.random() < 0.35:
        text = text[0].upper() + text[1:]
    return text


def code_dialogues(repeat: int, seed: int) -> List[List[Dict[str, str]]]:
    """
    Разворачивает банк задач в диалоги.

    Повторы намеренные. Обычно повторять примеры в корпусе вредно — модель
    заучивает их наизусть вместо того, чтобы обобщать. Здесь заучивать и надо:
    цель не в том, чтобы модель знала конкретную страницу с кнопкой, а в том,
    чтобы ФОРМА ответа стала для неё привычной. Формулировки при этом каждый раз
    разные, так что дословных дублей почти не возникает.
    """
    rng = random.Random(seed)
    rows: List[List[Dict[str, str]]] = []

    for task in TASKS:
        for ask in task["asks"]:
            for _ in range(repeat):
                opener = rng.choice(OPENERS)
                answer = f"{opener}\n\n```{task['lang']}\n{task['code']}\n```"
                # Пояснение после блока — не всегда: иначе модель приучится
                # приписывать его даже там, где сказать нечего.
                if task.get("note") and rng.random() < 0.8:
                    answer += f"\n\n{task['note']}"

                rows.append([
                    {"role": "system", "content": SYSTEM_ULTRA},
                    {"role": "user", "content": _vary_question(ask, rng)},
                    {"role": "assistant", "content": answer},
                ])

    return rows



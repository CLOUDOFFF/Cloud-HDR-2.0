"""
Cloud HDR AI — сборка корпуса для дообучения Cloud HDR Ultra.

Что дообучается и зачем.

Веса v5 умеют разговаривать: разговорный корпус на сорок тысяч диалогов сделал
своё дело. Кода они не видели ни строчки — и это не «пишет плохо», а гораздо
хуже. Замер на «напиши код html страницы с кнопкой» до дообучения: модель
открывает блок ```html, набирает четыре осмысленные строки, а дальше выдаёт
«</div>» тридцать раз подряд, пока не кончится бюджет. Незнакомый формат она не
отвергает — она в нём тонет.

Отсюда состав корпуса. Он собирается из трёх частей, и все три обязательны.

КОД. Полсотни задач из codebank.py, каждая в нескольких формулировках и с
разными вводными строками. Учится не программирование как таковое — на 760 млн
параметров этого не будет, — а ФОРМАТ ОТВЕТА: русская вводная строка, блок в
тройных кавычках с языком, закрывающие кавычки, строка о применении. Именно на
этот формат опирается и подсветка в чате, и правило остановки на сервере.

СТИХИ. Русская классика с Hugging Face, обёрнутая в просьбы вида «сочини
стихотворение про …». Здесь тоже важнее формат: строки в столбик и без
преамбулы. Модель и до этого умела рифмовать (болванка rugpt3 видела много
стихов), но на просьбу отвечала прозаическим пересказом замысла.

РАЗГОВОР. Выборка из прежнего корпуса — примерно вдвое больше, чем кода и стихов
вместе. Без неё дообучение сработало бы слишком хорошо: модель, увидевшая за
тысячу шагов только код, начинает отвечать кодом на «привет». Это называется
катастрофическим забыванием, и лечится оно ровно так — тем, что старое остаётся
в корпусе рядом с новым.

Системная подсказка у каждой части СВОЯ и в точности та, которую подставит
сервер (см. profiles.SYSTEM_ULTRA, SYSTEM_VERSE, SYSTEM_CHAT). Это не мелочь:
модель видит подсказку в каждом примере и приучается к тому, что за ней следует.
Обучи её на одной подсказке, а спрашивай с другой — и половина выученного
поведения не включится.

    python -m cloudhdr_ai ultra --out data/ultra.jsonl
"""

from __future__ import annotations

import json
import random
import re
from pathlib import Path
from typing import Any, Dict, List, Optional

from .branding import log, rule
from .codebank import OPENERS, TASKS
from .profiles import SYSTEM_CHAT, SYSTEM_ULTRA, SYSTEM_VERSE


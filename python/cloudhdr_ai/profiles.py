# ----------------------------------------------------------- род обращения --

#: Просьба написать код.
#:
#: Два независимых признака, и хватает любого. Первый — глагол-поручение рядом со
#: словом о программировании: так выглядит «напиши функцию на питоне». Второй —
#: прямое называние технологии: «html страница с формой» команды не содержит, но
#: ответ там всё равно кодом.
_CODE = re.compile(
    r"(?:(?:напиши|сделай|создай|сгенерируй|составь|покажи|набросай|дай|"
    r"перепиши|исправь|поправь|дополни|оформи)\W+(?:\w+\W+){0,4}?"
    r"(?:код|кода|скрипт\w*|программ\w*|функци\w*|класс\b|метод\b|"
    r"страниц\w*|сайт\w*|верстк\w*|разметк\w*|стил\w*|запрос\w*|алгоритм\w*|"
    r"регулярк\w*|бота\b|калькулятор\w*|форм[уы]\b))"
    r"|(?:\b(?:html|css|javascript|js|jsx|typescript|ts|python|питон\w*|"
    r"sql|json|xml|bash|powershell|батник|bat\b|си\+\+|c\+\+|c#|java\b|"
    r"react|vue|node|flask|django|numpy|pandas)\b)",
    re.IGNORECASE,
)

#: Просьба сочинить стихи.
_VERSE = re.compile(
    r"\b(стих\w*|стихотворени\w*|поэм\w*|четверостиши\w*|хайку|"
    r"в\s+рифму|срифм\w*|рифм\w*|балладу|оду\b|сонет\w*|песн[юи]\b)\b",
    re.IGNORECASE,
)

#: Просьба написать длинный текст: письмо, статью, рассказ, инструкцию.
_ESSAY = re.compile(
    r"(?:напиши|составь|сочини|подготовь|сделай)\W+(?:\w+\W+){0,3}?"
    r"(?:текст\w*|письмо|статью|рассказ\w*|сочинени\w*|инструкци\w*|"
    r"план\b|сценари\w*|описани\w*|пост\b|объявлени\w*|резюме)",
    re.IGNORECASE,
)

#: Вопрос «что это такое», а не просьба что-то написать.
#:
#: Нужен из-за второй половины _CODE, которая срабатывает на одно лишь название
#: технологии. Без этой проверки «расскажи про python» попадало бы в код: слово
#: есть, значит пишем программу. А спрашивают там определение — и отвечать на
#: него надо коротко, разговорным профилем и со справкой из Википедии.
#:
#: Проверка идёт по НАЧАЛУ фразы (match, а не search) намеренно: «расскажи, как
#: написать сайт на html» начинается с того же глагола, но это уже просьба о
#: коде, и она сюда не попадает — «расскажи» здесь без «о» и «про».
_EXPLAIN = re.compile(
    r"^\s*(?:что\s+так(?:ое|ая)|кто\s+так(?:ой|ая|ие)|расскажи\s+(?:мне\s+)?(?:о|про)\b|"
    r"что\s+значит|что\s+за\b|зачем\s+нужн\w*|для\s+чего\s+нужн\w*|чем\s+отлича\w*|"
    r"в\s+чём\s+разниц\w*)",
    re.IGNORECASE,
)

KIND_TALK = "talk"
KIND_CODE = "code"
KIND_VERSE = "verse"
KIND_ESSAY = "essay"


def kind_of(question: str) -> str:
    """Чего от модели хотят: разговора, кода, стихов или длинного текста."""
    text = str(question or "")
    # Порядок проверок — по «дороговизне ошибки».
    #
    # Стихи первыми: их спрашивают прямо, и «напиши стихотворение про питон»
    # содержит и слово «питон», и слово «стихотворение» — это всё-таки стихи.
    if _VERSE.search(text):
        return KIND_VERSE
    # Определение — вторым, и оно перебивает код: см. комментарий к _EXPLAIN.
    if _EXPLAIN.match(text):
        return KIND_TALK
    if _CODE.search(text):
        return KIND_CODE
    if _ESSAY.search(text):
        return KIND_ESSAY
    return KIND_TALK


# -------------------------------------------------------------- профили ----

#: Что умеет каждое имя из списка моделей.
#:
#: `kinds` — рода обращений, которые имя обслуживает по-своему. Всё, чего в
#: списке нет, обрабатывается как разговор: 3.2 на просьбу написать код не
#: откажется, а ответит как умеет — коротким разговорным ответом. Отказываться
#: было бы хуже: человек не обязан знать, какое имя за что отвечает.
PROFILES: Dict[str, Dict[str, Any]] = {
    MODEL_ID: {
        "label": MODEL_LABEL,
        "title": "Cloud HDR 3.2",
        "about": "Разговор, объяснения и точные факты из Википедии.",
        "kinds": (),
        "wiki": True,
    },
    MODEL_ID_ULTRA: {
        "label": MODEL_LABEL_ULTRA,
        "title": "Cloud HDR Ultra",
        "about": "Всё то же плюс код, разметка, стихи и длинные тексты.",
        "kinds": (KIND_CODE, KIND_VERSE, KIND_ESSAY),
        "wiki": True,
    },
}

DEFAULT_PROFILE = MODEL_ID


def resolve(model_id: Optional[str]) -> str:
    """
    Приводит имя из запроса к известному профилю.

    Незнакомое имя — не ошибка. Клиент мог остаться от прежней версии, где
    список моделей был другим, и ронять из-за этого разговор незачем: отвечаем
    разговорным профилем, он безопаснее.
    """
    name = str(model_id or "").strip().lower()
    if name in PROFILES:
        return name
    # «ultra» в любом виде — «Cloud HDR Ultra», «cloud-hdr-ultra», «Ultra».
    if "ultra" in name:
        return MODEL_ID_ULTRA
    return DEFAULT_PROFILE


# ---------------------------------------------------------------- бюджеты --

#: Сколько токенов отвести под ответ, если клиент не попросил иного.
#:
#: Числа не «на глаз», а от объёма, который род обращения физически требует:
#:   разговор  — четыре-шесть предложений, это 800-900 знаков;
#:   стихи     — восемь-двенадцать строк, знаков втрое меньше, но строки рвать
#:               нельзя, поэтому запас берём с избытком;
#:   текст     — статья или письмо, полторы-две тысячи знаков;
#:   код       — страница на html со стилями внутри не помещается ни во что
#:               меньшее, и здесь скупость выходит дороже всего.
BUDGET = {
    # 220, а не 320: при большем бюджете v7 заполняла место списками из
    # восьми пунктов там, где просили пару тёплых фраз («мне грустно»).
    KIND_TALK: 220,
    KIND_VERSE: 320,
    KIND_ESSAY: 560,
    KIND_CODE: 1100,
}

#: Запас сверх бюджета на то, чтобы ДОГОВОРИТЬ начатое.
#:
#: У разговора это остаток предложения — шестидесяти токенов хватает на длинную
#: русскую фразу. У кода это остаток блока, и он может быть каким угодно: сорок
#: строк функции — обычное дело. Отсюда разница в порядок.
GRACE = {
    KIND_TALK: 80,
    KIND_VERSE: 120,
    KIND_ESSAY: 90,
    KIND_CODE: 420,
}

#: Параметры выборки под каждый род обращения.
#:
#: Температура у кода низкая осознанно: код — единственное место, где «поживее»
#: означает «с опечатками в именах переменных». У стихов наоборот: на 0.4
#: получается рифмованный протокол, и поднять её здесь важнее, чем где-либо ещё.
SAMPLING = {
    # v7: замер на живом разговоре. На 0.7 модель путала имя («Михаил» вместо
    # «Мирослав») и уходила в нумерованные списки; на 0.55 имя и увлечение
    # называются верно полной фразой, а речь остаётся живой — живость v7
    # берёт из обучения, а не из температуры.
    KIND_TALK: {"temperature": 0.55, "top_p": 0.92, "top_k": 50},
    KIND_VERSE: {"temperature": 0.90, "top_p": 0.95, "top_k": 60},
    KIND_ESSAY: {"temperature": 0.55, "top_p": 0.94, "top_k": 40},
    # top_k=0 у кода — не забывчивость. Отбор сорока самых вероятных токенов
    # выбрасывает редкие, а имена в коде как раз редкие: «querySelectorAll»
    # набирается кусками, каждый из которых по отдельности маловероятен.
    # Ограничение по top_p оставляем — оно отсекает откровенный мусор, не
    # трогая длинный хвост технических слов.
    KIND_CODE: {"temperature": 0.25, "top_p": 0.90, "top_k": 0},
}

#: Штраф за повтор, если он должен отличаться от подобранного движком.
#:
#: None означает «оставить как есть»: движок подбирает штраф под словарь модели
#: замером (см. serve.choose_repetition_penalty), и для речи это верно.
#:
#: У кода — своё значение, и ниже общего. Код повторяется по самой своей природе:
#: отступы, закрывающие скобки, одинаковые начала строк. Наказывать за это —
#: значит подталкивать модель писать «поразнообразнее» ровно там, где
#: разнообразие есть ошибка. От зацикливания здесь защищает не штраф, а
#: отдельная проверка looping(): она смотрит на смысл повтора, а не на частоту
#: отдельного токена.
REPETITION = {
    KIND_TALK: None,
    KIND_VERSE: None,
    KIND_ESSAY: None,
    KIND_CODE: 1.05,
}

#: Правило остановки: чем должен кончиться законченный ответ.
FINISH = {
    KIND_TALK: "sentence",
    KIND_VERSE: "line",
    KIND_ESSAY: "sentence",
    KIND_CODE: "code",
}


def plan(model_id: Optional[str], question: str,
         requested_max_tokens: Optional[int] = None) -> Dict[str, Any]:
    """
    Собирает всё, что нужно для одного ответа.

    Возвращает словарь: system, temperature, top_p, top_k, max_tokens, grace,
    finish, wiki, kind, profile.

    Про `requested_max_tokens`. Клиент присылает свой предел, и раньше он был
    единственным. Теперь он трактуется как ПОЖЕЛАНИЕ, а не как приказ: если род
    обращения требует больше, берётся большее из двух. Иначе получалось бы, что
    страница на html обрывается из-за числа, которое клиент поставил, думая о
    разговорной реплике, — а он о ней и думал, потому что в момент отправки
    ещё не знает, чего попросили.
    """
    name = resolve(model_id)
    profile = PROFILES[name]

    # Родов обращения здесь ДВА, и это не запутанность, а разделение обязанностей.
    #
    #   asked  — чего попросили на самом деле;
    #   served — как это имя такую просьбу обслуживает.
    #
    # Для Ultra они совпадают. Для 3.2 served всегда «разговор»: она в длинный
    # режим не уходит, в этом весь смысл выбора между ними.
    #
    # Но правило остановки и запас берутся от ASKED — от того, что попросили, а
    # не от того, как мы решили это подать. Причина обнаружилась на замере сразу
    # после дообучения. Модель выучила формат кода так прочно, что на «напиши
    # код html» отвечает кодом ДАЖЕ в разговорном профиле — подсказку про код
    # она при этом не видит, ей хватает самого вопроса. А разговорное правило
    # ждёт точку, которой в разметке нет, и обрывает ответ на двухсотом токене:
    # «button:hover { background: #4a78e8; }» и дальше одинокая «<».
    #
    # То есть выбор «покороче» превращался в выбор «сломанный ответ». Так быть
    # не должно ни при каком выборе: короткий ответ — это законченный короткий
    # ответ, а не половина страницы. Бюджет остаётся разговорным, темпера тоже,
    # а вот дописать начатый блок модели разрешено при любом имени.
    asked = kind_of(question)
    served = asked if asked in profile["kinds"] else KIND_TALK

    sampling = dict(SAMPLING[served])
    budget = BUDGET[served]
    kind = served
    if requested_max_tokens:
        wanted = int(requested_max_tokens)
        # В разговоре слово клиента последнее: там он знает, чего хочет, не хуже
        # нас. В остальных родах его число — нижняя граница, а не верхняя.
        budget = wanted if kind == KIND_TALK else max(budget, wanted)

    # Подсказку выбирает РОД ОБРАЩЕНИЯ, а не имя модели.
    #
    # Сначала было иначе: Ultra получала подсказку про код на любую реплику, в
    # том числе на «привет». Рассуждение казалось стройным — «Ultra умеет код,
    # пусть про это и написано», — а на деле давало ровно обратное.
    #
    # Во-первых, это расхождение обучения и работы. В корпусе (ultra.py)
    # разговорные диалоги стоят с разговорной подсказкой, а подсказка про код —
    # только рядом с кодом. Модель на 760M связывает их напрямую: увидела абзац
    # про тройные кавычки — значит, сейчас пишем программу. Подставлять его на
    # «как дела» значит подталкивать её к коду там, где его не просили.
    #
    # Во-вторых, из-за этого Ultra была бы ХУЖЕ 3.2 в разговоре — при том, что
    # выбирают её как «то же самое плюс код». Так быть не должно: на обычном
    # вопросе обе обязаны отвечать одинаково, буква в букву.
    # Длинный текст (письмо, статья, план) идёт с РАЗГОВОРНОЙ подсказкой, а не с
    # ультровой. Сначала было наоборот — «Ultra же, пусть знает про код», — и на
    # замере вылезло вот что: письмо начальнику открывалось словами «Вот рабочий
    # вариант:». Это вводная строка из обучающих примеров с кодом, и модель
    # притащила её за подсказкой, в которой про код написано. Письму она ни к
    # чему; больше в подсказке для кода ничего полезного тексту нет.
    system = {
        KIND_CODE: SYSTEM_ULTRA,
        KIND_ESSAY: SYSTEM_CHAT,
        KIND_VERSE: SYSTEM_VERSE,
        KIND_TALK: SYSTEM_CHAT,
    }[kind]

    return {
        "profile": name,
        "label": profile["label"],
        "kind": kind,
        "asked": asked,
        "system": system,
        "max_tokens": budget,
        # Запас и правило остановки — от того, ЧТО попросили (asked), а не от
        # того, как имя это подаёт (served). Подробно почему — выше.
        "grace": GRACE[asked],
        "finish": FINISH[asked],
        "repetition_penalty": REPETITION[asked],
        # Справка из Википедии уместна только в разговоре. На «напиши код
        # сортировки» статья «Сортировка» подставила бы определение вместо
        # программы — и это ровно тот случай, когда помощь мешает.
        "wiki": bool(profile["wiki"]) and kind == KIND_TALK,
        **sampling,
    }


# ------------------------------------------------- когда ответ можно кончить --

#: Чем кончается законченная мысль в обычной речи.
SENTENCE_ENDS = (".", "!", "?", "…", ".»", "!»", "?»", '."', '!"', '?"', ".)", "!)", "?)")

#: Чем кончается законченная строка кода.
#:
#: Точки у кода нет, а есть закрытая скобка, закрытый тег и точка с запятой.
#: Именно из-за того, что раньше ждали точку, ответ с программой досиживал весь
#: запас и обрывался ровно там, где запас кончился.
CODE_ENDS = ("}", ");", ";", ">", "]", "```", ".")

#: Парные теги, по которым видно, что разметка ещё не дописана.
#:
#: Список короткий и только структурный. Взять «все теги» нельзя: <p>, <li> и
#: <br> в живой разметке закрывают не всегда, и такая проверка держала бы ответ
#: открытым до последнего токена запаса на ровном месте. А вот <html> без
#: </html> — это всегда обрыв.
_PAIRED_TAGS = (
    "html", "head", "body", "style", "script", "div", "form", "table",
    "tbody", "thead", "select", "textarea", "section", "header", "footer",
    "main", "nav", "ul", "ol", "canvas", "svg", "button",
)


def _fence_open(text: str) -> bool:
    """Открыт ли сейчас блок ``` — то есть нельзя ли останавливаться."""
    return text.count("```") % 2 == 1


def _brackets_open(text: str) -> bool:
    """
    Остались ли незакрытые скобки в коде.

    Считаем грубо и намеренно: кавычки и комментарии не разбираем, потому что
    полноценный разбор четырёх языков здесь не нужен, а лишний виток генерации
    стоит дешевле оборванной функции. Ошибка возможна только в одну сторону —
    «подождать ещё немного», и это ровно та сторона, в которую ошибаться не жалко.
    """
    return (text.count("{") > text.count("}")
            or text.count("(") > text.count(")")
            or text.count("[") > text.count("]"))


def _tags_open(text: str) -> bool:
    """Есть ли открытый парный тег разметки."""
    if "<" not in text:
        return False
    lowered = text.lower()
    for tag in _PAIRED_TAGS:
        # Заглядывание вперёд обязательно: без него «<head» нашлось бы внутри
        # «<header», и разметка с шапкой страницы считалась бы вечно открытой.
        # Оно же покрывает и «<div>», и «<div class=…>», и «<br/>», поэтому
        # отдельно считать «<tag>» не нужно — иначе каждый такой тег попал бы в
        # счёт дважды, и закрытая разметка выглядела бы незакрытой.
        opened = len(re.findall(rf"<{tag}(?=[\s>/])", lowered))
        closed = lowered.count(f"</{tag}>")
        if opened > closed:
            return True
    return False


#: Сколько повторов подряд считать зацикливанием.
#:
#: Четыре, а не два и не десять. Два — это нормальный код: две подряд закрытых
#: скобки, две пустых строки, два одинаковых пункта списка. Десять — это уже
#: полэкрана мусора, и обрывать там поздно.
_LOOP_REPEATS = 4

#: Сколько последних знаков рассматривать.
_LOOP_WINDOW = 400


def looping(text: str) -> bool:
    """
    Модель зациклилась: хвост состоит из повторов одного и того же.

    Зачем это здесь. У маленькой модели на незнакомой задаче есть характерный
    способ ломаться: она не замолкает, а начинает повторять последнюю строку до
    конца бюджета. На просьбе о вёрстке до дообучения это выглядело так —
    полстраницы подряд «</div>», и весь запас в четыреста токенов уходил на них.

    Правило остановки этого не ловит и поймать не может: незакрытых тегов при
    таком повторе становится только больше, то есть с его точки зрения ответ всё
    время «ещё не дописан». Поэтому проверка отдельная.

    Считается по тексту, а не по токенам, и это осознанно: один и тот же повтор
    модель может набрать разными разбиениями на токены, а глазами он один.
    """
    tail = text[-_LOOP_WINDOW:]

    lines = [line.strip() for line in tail.split("\n") if line.strip()]
    if len(lines) >= _LOOP_REPEATS and len(set(lines[-_LOOP_REPEATS:])) == 1:
        return True

    # Повтор без переводов строки: «абвабвабвабв». Длину куска перебираем
    # снизу вверх — короткий повтор и вероятнее, и заметнее.
    stripped = tail.rstrip()
    for size in range(3, 41):
        if len(stripped) < size * _LOOP_REPEATS:
            break
        chunk = stripped[-size:]
        # Кусок из одного и того же знака — это разделитель («--------»,
        # «======»), а не зацикливание. Без этой проверки любая черта в тексте
        # обрывала бы ответ на середине.
        if len(set(chunk)) < 2:
            continue
        if stripped.endswith(chunk * _LOOP_REPEATS):
            return True
    return False


def can_finish(text: str, style: str) -> bool:
    """
    Можно ли считать ответ законченным прямо сейчас.

    Вызывается ТОЛЬКО после того, как бюджет исчерпан: пока токены есть,
    генерация идёт своим чередом. Дальше начинается запас, и здесь решается,
    израсходовать его целиком или остановиться раньше.
    """
    tail = text.rstrip()
    if not tail:
        return False

    if style == "line":
        # Стихи: строка кончилась переводом строки — этого достаточно.
        return text.endswith("\n") or tail.endswith(SENTENCE_ENDS)

    if style == "code":
        if _fence_open(text) or _brackets_open(text) or _tags_open(text):
            return False
        return tail.endswith(CODE_ENDS)

    # Незакрытый блок ``` не даёт закончить ответ НИ ПРИ КАКОМ правиле.
    #
    # Это подстраховка поверх выбора запаса в plan(). Она дешёвая — одна
    # проверка на токен, — и закрывает случай, до которого рассуждение о родах
    # обращения не дотягивается: вопрос не выглядел просьбой о коде, а модель
    # всё равно открыла блок. Оборванный на середине блок кода — самая заметная
    # из возможных поломок, и оставлять её на «ну, это же не код-режим» нельзя.
    if _fence_open(text):
        return False

    return tail.endswith(SENTENCE_ENDS)

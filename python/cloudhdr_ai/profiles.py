"""
Cloud HDR AI — два имени у одних весов: Cloud HDR 3.2 и Cloud HDR Ultra.

Что здесь решается. Модель в проекте одна — 760 млн параметров, один файл весов,
один экземпляр в видеопамяти. Но задачи, которые ей ставят, разные настолько, что
одни и те же настройки генерации на них работать не могут:

    «почему небо голубое»      короткий ответ, низкая температура, справка
                               из Википедии дословно — тут важна точность
    «напиши страницу на html»  длинный ответ, ещё более низкая температура,
                               никакой Википедии, и обрывать по концу
                               предложения нельзя: у кода предложений нет
    «сочини стихотворение»     высокая температура, иначе выходит рифмованная
                               канцелярия, и обрывать по точке тоже неверно —
                               строфа кончается строкой, а не точкой

Прежде параметры были одни на всё и подбирались под первый случай. Отсюда и
жалобы на код: он обрывался на середине не из-за модели, а из-за правила
остановки, написанного для разговорной фразы.

Поэтому здесь — планировщик. Он получает имя выбранной модели и сам вопрос, а
возвращает готовый набор: системную подсказку, параметры генерации и правило,
по которому ответ можно считать законченным.

Ровно один принцип, ради которого всё это писалось: РЕШЕНИЕ О ДЛИНЕ ОТВЕТА
ПРИНИМАЕТСЯ ДО ГЕНЕРАЦИИ, А РЕШЕНИЕ ОБ ОСТАНОВКЕ — ПОСЛЕ. Бюджет ограничивает
объём, правило остановки следит за целостностью, и второе имеет право
перевесить первое. Незакрытый тег <style> или половина функции — это не
«короткий ответ», это сломанный ответ.
"""


#: позиции системной реплики в каждом обучающем диалоге, и переписать её значило
#: бы дать формат, которого при обучении не было. Поэтому добавка идёт хвостом —
#: тем же приёмом, что и в SYSTEM_ULTRA ниже.
#:
#: Зачем добавка. В обучающий корпус попали 667 диалогов из корпуса

#: Разделители строк, которые Unicode считает переводом строки, а JSON — обычным
#: символом внутри строки. Приводим их к \n при сборке, чтобы текст был ровно
#: тем, чем выглядит, и не зависел от того, какой функцией его потом разрежут.
_EXOTIC_BREAKS = re.compile("[\x0b\x0c\x1c-\x1e\x85\u2028\u2029]")


def _clean(text: str) -> str:
    text = _EXOTIC_BREAKS.sub("\n", str(text or ""))
    text = re.sub(r"[ \t]+", " ", text).strip()
    return re.sub(r"\n{3,}", "\n\n", text)


def _messages_from(raw: Any, min_chars: int, max_chars: int) -> Optional[List[Dict[str, str]]]:
    """
    Чужой список сообщений → диалог Cloud HDR, либо None, если он не годится.

    Отбраковка, а не обрезка. Слишком длинную реплику можно было бы укоротить, но
    обрубленный на середине ответ учит модель ровно тому, чего от неё не хотят, —
    обрывать мысль. Предел в полторы тысячи знаков выбран под размер модели: это
    примерно 350 токенов, абзац-другой связного текста. Ответы длиннее модель на
    125M всё равно не удержит — начнёт повторяться и терять нить.
    """
    if not isinstance(raw, list):
        return None

    messages = normalize_dialogue([
        {"role": message.get("role"), "content": _clean(message.get("content"))}
        for message in raw if isinstance(message, dict)
    ])

    if not any(m["role"] == "assistant" for m in messages):
        return None
    if not any(m["role"] == "user" for m in messages):
        return None
    if any(len(m["content"]) > max_chars for m in messages):
        return None
    if sum(len(m["content"]) for m in messages) < min_chars:
        return None

    # Своя системная подсказка — только там, где источник не принёс собственной.
    if messages[0]["role"] != "system":
        messages.insert(0, {"role": "system", "content": SYSTEM_PROMPT})
    return messages


def _collect_saiga(
    limit: int,
    min_score: int,
    min_chars: int,
    max_chars: int,
    topic_cap: float,
    multiturn_share: float,
    chat_max_chars: int = 700,
    explain_max_chars: int = 1300,
) -> tuple:
    """
    Отбирает из saiga_scored широкий и сбалансированный срез разговоров.

    Три решения, которые определяют, чему научится модель.

    ОЦЕНКА. В наборе лежит оценка каждого диалога (opus_score, 1–10) и пометка
    is_bad_by_regex. Берём от восьми и выше: это отсекает примерно десятую часть
    записей, где ответ невпопад или оборван. Учить маленькую модель на плохих
    ответах особенно дорого — ей не хватит ёмкости, чтобы «понять» их как
    исключение, она просто переймёт манеру.

    БАЛАНС ПО ТЕМАМ. Без ограничения программирование заняло бы пятую часть
    корпуса: в исходном потоке его 21%, вдвое больше следующей темы. Модель на
    125M писать код всё равно не научится, зато перекос сместил бы ей манеру
    речи на всех остальных вопросах. Поэтому доля одной темы ограничена сверху,
    и в корпус попадают все два десятка — от науки до готовки.

    МНОГОХОДОВЫЕ ВНЕ ОЧЕРЕДИ. Разговоров с продолжением в потоке около четверти,
    и лимит по теме на них не распространяется: именно они учат держать нить,
    чего одноходовые пары не дают в принципе.

    ДЛИНА ПО ТЕМЕ. Три яруса (см. LONG_FORM_TOPICS и EXPLANATORY_TOPICS): разбор,
    объяснение и разговор. На «как настроение» ответ в две тысячи знаков — не
    подробность, а порча разговора и собственного контекста модели; на «почему
    нужно спать восемь часов» ответ в семьсот знаков — уже огрызок.
    """
    from datasets import load_dataset

    name, conf, _ = DIALOGUE_SOURCES["saiga"]
    stream = load_dataset(name, conf, split="train", streaming=True)

    cap = max(1, int(limit * topic_cap))
    single_quota = max(0, limit - int(limit * multiturn_share))

    topics: Counter = Counter()
    kept: List[tuple] = []
    spare: List[tuple] = []          # запас на случай, если многоходовых мало
    singles = 0
    scanned = 0
    multiturn = 0

    for row in stream:
        scanned += 1
        if len(kept) >= limit or scanned > SCAN_LIMIT:
            break
        if row.get("language") != "Russian" or row.get("is_bad_by_regex"):
            continue
        if (row.get("opus_score") or 0) < min_score:
            continue

        topic = str(row.get("sonnet_topic") or "other")
        if topic in LONG_FORM_TOPICS:
            ceiling = max_chars
        elif topic in EXPLANATORY_TOPICS:
            ceiling = min(max_chars, explain_max_chars)
        else:
            ceiling = min(max_chars, chat_max_chars)

        messages = _messages_from(row.get("messages"), min_chars, ceiling)
        if messages is None:
            continue

        replies = sum(1 for m in messages if m["role"] == "assistant")

        if replies >= 2:
            kept.append((messages, topic))
            topics[topic] += 1
            multiturn += 1
        elif singles < single_quota and topics[topic] < cap:
            kept.append((messages, topic))
            topics[topic] += 1
            singles += 1
        elif len(spare) < limit:
            spare.append((messages, topic))

        if scanned % 25000 == 0:
            log(f"  просмотрено {scanned:>6} · отобрано {len(kept):>5} "
                f"(многоходовых {multiturn})")

    # Многоходовых в потоке могло оказаться меньше зарезервированного — добираем
    # из запаса, иначе корпус вышел бы меньше заказанного без всякой причины.
    while len(kept) < limit and spare:
        messages, topic = spare.pop()
        kept.append((messages, topic))
        topics[topic] += 1

    records = [{"messages": messages} for messages, _ in kept]
    return records, {"topics": topics, "multiturn": multiturn, "scanned": scanned}


def _iter_instruct(limit: int, min_chars: int, max_chars: int) -> Iterable[Dict[str, Any]]:
    """alpaca-cleaned-ru: instruction + input → вопрос, output → ответ."""
    from datasets import load_dataset

    name, conf, _ = DIALOGUE_SOURCES["instruct"]
    stream = load_dataset(name, conf, split="train", streaming=True)
    taken = 0
    for row in stream:
        if taken >= limit:
            return
        instruction = _clean(row.get("instruction"))
        extra = _clean(row.get("input"))
        answer = _clean(row.get("output"))
        if not instruction or not answer:
            continue
        question = f"{instruction}\n{extra}" if extra else instruction
        if len(question) < min_chars or len(answer) < min_chars:
            continue
        if len(question) > max_chars or len(answer) > max_chars:
            continue
        taken += 1
        yield _pair(question, answer)


def _iter_chat(limit: int, min_chars: int, max_chars: int) -> Iterable[Dict[str, Any]]:
    """russian_dialogues: короткие вопрос-ответ живой речи."""
    from datasets import load_dataset

    name, conf, _ = DIALOGUE_SOURCES["chat"]
    stream = load_dataset(name, conf, split="train", streaming=True)
    taken = 0
    for row in stream:
        if taken >= limit:
            return
        question = _clean(row.get("question"))
        answer = _clean(row.get("answer"))
        if not question or not answer:
            continue
        if len(question) < min_chars or len(answer) < min_chars:
            continue
        if len(question) > max_chars or len(answer) > max_chars:
            continue

        # В наборе есть поле релевантности: пары с низкой оценкой — это шум,
        # и учить на них диалогу значит учить отвечать невпопад.
        relevance = row.get("relevance")
        try:
            if relevance is not None and float(relevance) < 0.5:
                continue
        except (TypeError, ValueError):
            pass

        taken += 1
        yield _pair(question, answer)



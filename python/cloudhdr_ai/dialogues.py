def build(
    out: str = "data/dialogues.jsonl",
    saiga: int = 30000,
    instruct: int = 8000,
    chat: int = 6000,
    persona_repeat: int = 12,
    drills: int = 700,
    min_chars: int = 12,
    max_chars: int = 2500,
    chat_max_chars: int = 700,
    explain_max_chars: int = 1300,
    min_score: int = 8,
    topic_cap: float = 0.10,
    multiturn_share: float = 0.35,
    seed: int = 20260808,
) -> dict:
    """
    Собирает диалоговый корпус в .jsonl, который понимает data.load_documents.

    :param saiga: сколько разговоров взять из saiga_scored — источника широты тем
    :param persona_repeat: сколько копий делать с каждого диалога о личности.
        Полсотни фраз против сорока тысяч — это доля процента, и без повторов
        модель их просто не заметит. Повтор поднимает их до заметной величины,
        но не даёт перевесить остальное.
    :param drills: сколько породить разговоров на память (см. memory_drills)
    :param min_score: нижняя граница оценки качества диалога в saiga_scored (1–10)
    :param max_chars: предел длины реплики для тем, где разбор требует места
    :param chat_max_chars: тот же предел для разговорных тем — он строже, потому
        что длинный ответ на короткую реплику портит и разговор, и контекст
    :param explain_max_chars: средний ярус — темы, где спрашивают «почему» и «как»
    :param topic_cap: предел доли одной темы в срезе Saiga
    :param multiturn_share: какую долю мест отвести под многоходовые разговоры
    """
    rng = random.Random(seed)
    path = Path(out)
    path.parent.mkdir(parents=True, exist_ok=True)

    records: List[Dict[str, Any]] = []
    report: Dict[str, Any] = {}

    rule("Личность")
    for _ in range(persona_repeat):
        records.extend(PERSONA)
    log(f"диалогов о самом себе: {len(PERSONA)} × {persona_repeat} = {len(records)}")
    report["persona"] = len(records)

    if drills > 0:
        rule("Память в разговоре")
        added = memory_drills(drills, seed=seed + 3)
        records.extend(added)
        turns_in_drills = sum(
            sum(1 for m in d["messages"] if m["role"] == "assistant") for d in added
        )
        log(f"разговоров с опорой на сказанное раньше: {len(added)} "
            f"· реплик модели в них: {turns_in_drills}")
        log("значения (имена, города, профессии) не пересекаются с проверочными — "
            "иначе проверка памяти перестала бы что-либо измерять")
        report["drills"] = len(added)

    if saiga > 0:
        rule("Широкие темы")
        log(f"качаю {DIALOGUE_SOURCES['saiga'][0]} (до {saiga}, оценка от {min_score})...")
        log(f"предел длины реплики: {max_chars} знаков на разбор, "
            f"{explain_max_chars} на объяснение, {chat_max_chars} на разговор")
        added, stats = _collect_saiga(
            saiga, min_score, min_chars, max_chars, topic_cap, multiturn_share,
            chat_max_chars, explain_max_chars,
        )
        records.extend(added)
        log(f"взято: {len(added)} · многоходовых: {stats['multiturn']} "
            f"({100 * stats['multiturn'] / max(len(added), 1):.0f}%) · "
            f"просмотрено записей: {stats['scanned']}")
        log(f"тем в корпусе: {len(stats['topics'])}")
        log("  " + " · ".join(f"{topic} {count}"
                              for topic, count in stats["topics"].most_common(12)))
        report["saiga"] = len(added)
        report["topics"] = len(stats["topics"])
        report["multiturn"] = stats["multiturn"]

    if instruct > 0:
        rule("Инструкции")
        log(f"качаю {DIALOGUE_SOURCES['instruct'][0]} (до {instruct})...")
        added = list(_iter_instruct(instruct, min_chars, max_chars))
        records.extend(added)
        log(f"взято: {len(added)}")
        report["instruct"] = len(added)

    if chat > 0:
        rule("Живые диалоги")
        log(f"качаю {DIALOGUE_SOURCES['chat'][0]} (до {chat})...")
        # Живые диалоги разговорные по определению — предел тот же, что у
        # разговорных тем Saiga, иначе сюда протекут длинные форумные простыни.
        added = list(_iter_chat(chat, min_chars, chat_max_chars))
        records.extend(added)
        log(f"взято: {len(added)}")
        report["chat"] = len(added)

    rng.shuffle(records)
    with path.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")

    turns = sum(
        sum(1 for m in record["messages"] if m["role"] == "assistant")
        for record in records
    )
    size_mb = path.stat().st_size / (1024 * 1024)
    rule("Готово")
    log(f"диалогов: {len(records)} · реплик модели: {turns} · {size_mb:.1f} МБ · {path}")
    log("Дальше: python -m cloudhdr_ai train --data data/dialogues.jsonl --from-brain "
        "--out checkpoints/v2 --dropout 0.1")

    report.update({"records": len(records), "turns": turns,
                   "path": str(path), "mb": round(size_mb, 1)})
    return report

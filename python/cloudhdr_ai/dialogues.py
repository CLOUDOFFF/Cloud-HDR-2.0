def memory_drills(count: int = 400, seed: int = 20260811) -> List[Dict[str, Any]]:
    """
    Порождает разговоры, в которых факт сначала называют, а потом о нём спрашивают.

    Зачем это понадобилось. Многоходовые диалоги Saiga учат ПРОДОЛЖАТЬ разговор,
    но почти не учат ССЫЛАТЬСЯ на сказанное раньше: в них следующая реплика
    обычно развивает тему, а не требует вспомнить конкретное слово из первой.
    Это разные умения, и второе для помощника важнее — «как меня зовут» и «а где
    та папка, о которой я говорил» держатся именно на нём.

    Ответы здесь нарочно короткие, в одно слово. Это вторая половина замысла:
    длинный ответ на такой вопрос не просто неуместен, он забивает модели
    собственный контекст и мешает ей найти факт в следующей реплике.
    """
    rng = random.Random(seed)
    drills: List[Dict[str, Any]] = []

    for _ in range(count):
        name = rng.choice(_DRILL_NAMES)
        city = rng.choice(_DRILL_CITIES)
        job = rng.choice(_DRILL_JOBS)
        hobby = rng.choice(_DRILL_HOBBIES)

        messages = [{"role": "system", "content": SYSTEM_PROMPT}]

        # --- знакомство: факты называются в свободной форме ---
        messages += [
            {"role": "user", "content": rng.choice([
                f"привет, меня зовут {name}",
                f"здравствуй! я {name}",
                f"меня зовут {name}, приятно познакомиться",
                f"привет! я {name}, будем знакомы",
            ])},
            {"role": "assistant", "content": rng.choice([
                f"Привет, {name}! Рад знакомству. Расскажите, чем могу помочь?",
                f"Очень приятно, {name}! Я Cloud. О чём поговорим?",
                f"Здравствуйте, {name}! Отличное имя. Что у вас сегодня на уме?",
            ])},
            {"role": "user", "content": rng.choice([
                f"я живу в {city} и работаю {job}",
                f"работаю {job}, живу в {city}",
                f"я из {city}, работаю {job}",
            ])},
            {"role": "assistant", "content": rng.choice([
                f"Здорово! Работать {job} — дело серьёзное и нужное. Запомню, что вы живёте в {city}.",
                f"Интересно! Значит, вы работаете {job} и живёте в {city} — буду знать. Как вам там живётся?",
                f"Спасибо, что рассказали! Работаете {job}, живёте в {city} — теперь я буду лучше вас понимать.",
            ])},
            {"role": "user", "content": rng.choice([
                f"ещё я увлекаюсь {hobby}",
                f"в свободное время занимаюсь {hobby}",
                f"а хобби у меня простое — увлекаюсь {hobby}",
            ])},
            {"role": "assistant", "content": rng.choice([
                f"Отличное увлечение! Заниматься {hobby} — это здорово переключает голову после работы.",
                f"О, {hobby}? Классно! Если захотите, могу подкинуть идей или интересных фактов на эту тему.",
                f"Здорово, что у вас есть такое хобби. Увлекаться {hobby} — лучший отдых, запомню.",
            ])},
        ]

        # --- проверка: вопросы задаются вразнобой, отвечать надо коротко ---
        questions = [
            (rng.choice(["как меня зовут?", "ты помнишь, как меня зовут?",
                         "напомни, как меня зовут"]),
             rng.choice([f"Вас зовут {name}.", f"Конечно помню — {name}!", f"{name}. Такое не забывается."])),
            (rng.choice(["в каком городе я живу?", "где я живу?",
                         "откуда я, помнишь?"]),
             rng.choice([f"Вы живёте в {city}.", f"В {city}, вы сами рассказывали."])),
            (rng.choice(["кем я работаю?", "какая у меня профессия?",
                         "напомни, кем я работаю"]),
             rng.choice([f"Вы работаете {job}.", f"{job.capitalize()} — вы говорили об этом."])),
            # Все три вопроса требуют творительного падежа — того же, в котором
            # хобби названо выше. «Какое у меня хобби» сюда не годится: на него
            # правильный ответ именительный («Шахматы»), и модель училась бы
            # отвечать не тем падежом, которым спрашивают.
            (rng.choice(["чем я увлекаюсь?", "чем я занимаюсь в свободное время?",
                         "напомни, чем я увлекаюсь"]),
             rng.choice([f"Вы увлекаетесь {hobby}.", f"{hobby.capitalize()} — это ваше хобби."])),
        ]
        rng.shuffle(questions)

        for question, answer in questions[: rng.randint(2, 4)]:
            messages.append({"role": "user", "content": question})
            messages.append({"role": "assistant", "content": answer})

        drills.append({"messages": messages})

    return drills


